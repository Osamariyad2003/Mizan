def contents(pages: dict[str, int] | None) -> list:
    """The contents page. `pages` maps heading text to page number (pass two)."""
    body = [p("Contents", "h1")]
    for title, page in (pages or {}).items():
        if title == "Contents":  # the contents page does not list itself
            continue
        number, _, name = title.partition("  ")
        dots = "&nbsp;.&nbsp;" * 3
        body.append(Paragraph(
            f"<font color='#6b6862'>{number}</font>&nbsp;&nbsp;{name}"
            f"<font color='#6b6862'> {dots} {page}</font>", S["toc"]))
    if not pages:
        body.append(p("(page numbers are filled in on the second pass)", "small"))
    body.append(PageBreak())
    return body


