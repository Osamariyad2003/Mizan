def story(pages: dict[str, int] | None = None) -> list:
    """All flowables, in order. `pages` comes from the first build pass."""
    from sections_ops import (
        appendix_files,
        appendix_glossary,
        section_config,
        section_data_flow,
        section_interfaces,
        section_limits,
        section_measurement,
        section_testing,
    )
    from sections_pipeline import (
        section_arabic,
        section_articles,
        section_chunking,
        section_embedding,
        section_generation,
        section_index,
        section_reading,
        section_rerank,
        section_retrieval,
    )

    parts = [
        cover, contents, section_overview, section_architecture, section_stack,
        section_reading, section_arabic, section_articles, section_chunking,
        section_embedding, section_index, section_retrieval, section_rerank,
        section_generation, section_data_flow, section_interfaces, section_config,
        section_measurement, section_testing, section_limits,
        appendix_files, appendix_glossary,
    ]
    flowables = []
    for part in parts:
        flowables.extend(part(pages) if part is contents else part())
    return flowables
