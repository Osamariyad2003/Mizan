"""Generate the line-by-line code walkthrough PDF.

    python docs/make_code_pdf.py      # -> docs/RAG-code-walkthrough.pdf

Every module listed in MODULES is printed in full, with line numbers, broken
into blocks that each carry an explanation. walkthrough.check_coverage refuses
to build if the blocks leave any line unexplained, so the document stays
complete as the code changes.
"""

from __future__ import annotations

import importlib
from pathlib import Path

from reportlab.platypus import PageBreak, Paragraph, Spacer
from reportlab.lib.units import mm

from make_pdf import S, Doc, bullets, p, panel, table
from walkthrough import module_section, source_lines

OUT = Path(__file__).resolve().parent / "RAG-code-walkthrough.pdf"

# Reading order: settings first, then the ingestion path, then the query path,
# then the interfaces - the order data actually flows through the system.
MODULES = [
    ("rag/config.py", "notes_config"),
    ("rag/loaders.py", "notes_loaders"),
    ("rag/arabic.py", "notes_arabic"),
    ("rag/legal.py", "notes_legal"),
    ("rag/chunking.py", "notes_chunking"),
    ("rag/embeddings.py", "notes_embeddings"),
    ("rag/bm25.py", "notes_bm25"),
    ("rag/store.py", "notes_store"),
    ("rag/retriever.py", "notes_retriever"),
    ("rag/crossencoder.py", "notes_crossencoder"),
    ("rag/llm.py", "notes_llm"),
    ("rag/generate.py", "notes_generate"),
    ("rag/rerank.py", "notes_rerank"),
    ("rag/pipeline.py", "notes_pipeline"),
    ("rag/cli.py", "notes_cli"),
    ("rag/server.py", "notes_server"),
    ("rag/__init__.py", "notes_init"),
]

W = 165 * mm


def cover(total_lines: int, module_count: int) -> list:
    return [
        Spacer(1, 38 * mm),
        p("The Code, Line by Line", "title"),
        Spacer(1, 6 * mm),
        p("Every line of the retrieval-augmented generation system over Jordanian "
          "legislation, printed with its line number and explained.", "subtitle"),
        Spacer(1, 14 * mm),
        table([
            ["Covered", f"{total_lines:,} lines across {module_count} modules - the complete "
                        f"rag/ package"],
            ["Format", "Source with line numbers, in blocks, each block followed by what it "
                       "does and why"],
            ["Guarantee", "The generator refuses to build unless the notes cover every line of "
                          "every module: no gaps, no overlaps"],
            ["Companion", "RAG-system-explained.pdf covers the architecture and the data flow; "
                          "this document covers the code itself"],
        ], [W * 0.18, W * 0.82], header=False),
        Spacer(1, 10 * mm),
        p("Generated by <font name='Mono' size='8.5'>docs/make_code_pdf.py</font> directly from "
          "the source files.", "small"),
    ]


def preface() -> list:
    return [
        p("How to read this document", "h1"),
        p("Each module begins with a one-paragraph summary of its job. The source then follows "
          "in blocks: the real code with its real line numbers, then a paragraph explaining "
          "what those lines do. Individual lines are called out in <b>bold</b> inside the "
          "explanation where they deserve their own sentence."),
        *bullets([
            "<b>Nothing is skipped.</b> The blocks are checked to tile each file exactly, so "
            "imports, blank lines and closing brackets are all inside some block. Where a run "
            "of lines is self-evident, the block note covers them together rather than "
            "repeating the obvious.",
            "<b>The code is read from disk at build time.</b> Nothing here is retyped, so the "
            "listing cannot drift from what actually runs.",
            "<b>Explanations favour the reason over the mechanism.</b> That a line assigns a "
            "variable is visible; why the variable exists, and what breaks without it, is not.",
        ]),
        p("The reading order follows the data: settings, then the ingestion path (reading "
          "documents, repairing Arabic, finding articles, chunking, embedding, storing), then "
          "the query path (retrieval, reranking, the model, the answer), then the interfaces "
          "that tie them together."),
        panel("<b>If a line looks strange, it usually has a story.</b> Several lines in this "
              "code exist because of a specific failure: a Windows file lock, a PDF that "
              "extracts backwards, an index that could silently misalign with its vectors. "
              "Those notes say so, because the alternative is a future reader removing the line."),
        PageBreak(),
    ]


def contents(pages: dict[str, int] | None, counts: dict[str, int]) -> list:
    """Module list with page numbers. `pages` is filled in on the second pass."""
    body = [p("Contents", "h1")]
    for module, _ in MODULES:
        page = (pages or {}).get(module)
        dots = "&nbsp;.&nbsp;" * 3
        tail = f"{dots} {page}" if page else ""
        body.append(Paragraph(
            f"<font name='Mono' size='8.5'>{module}</font>"
            f"<font color='#6b6862'>&nbsp;&nbsp;{counts[module]} lines {tail}</font>",
            S["toc"]))
    if not pages:
        body.append(p("(page numbers are filled in on the second pass)", "small"))
    body.append(PageBreak())
    return body


def story(pages: dict[str, int] | None = None) -> list:
    sections: list = []
    counts: dict[str, int] = {}
    for module, notes_module in MODULES:
        notes = importlib.import_module(notes_module)
        counts[module] = len(source_lines(module))
        sections.extend(module_section(module, notes.SUMMARY, notes.BLOCKS))
    flow: list = cover(sum(counts.values()), len(MODULES))
    flow.append(PageBreak())
    flow.extend(preface())
    flow.extend(contents(pages, counts))
    flow.extend(sections)
    return flow


def build() -> None:
    """Build twice: the first pass only to learn where each module landed."""
    import tempfile

    scratch = Path(tempfile.gettempdir()) / "rag-code-pass1.pdf"
    first = Doc(str(scratch))
    first.build(story())
    pages = {title: page for title, page in first.headings}
    Doc(str(OUT)).build(story(pages))
    scratch.unlink(missing_ok=True)
    print(f"wrote {OUT} ({OUT.stat().st_size/1024:.0f} KB)")


if __name__ == "__main__":
    build()
